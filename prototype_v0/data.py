# Типы по кругу: каждый бьёт следующего x2, а от предыдущего получает x0.5
TYPES = ["Помойка", "Подвал", "Улица", "Дикий"]


def type_mult(att, dfn):
    if att is None:
        return 1.0
    i, j = TYPES.index(att), TYPES.index(dfn)
    if (i + 1) % len(TYPES) == j:
        return 2.0
    if (j + 1) % len(TYPES) == i:
        return 0.5
    return 1.0


